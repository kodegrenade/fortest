import type { ReactElement, SVGProps } from 'react';

interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number;
  className?: string;
}

function makeIcon(
  render: (props: IconProps) => ReactElement,
  displayName: string
) {
  const Icon = (props: IconProps) => render(props);
  Icon.displayName = displayName;
  return Icon;
}

